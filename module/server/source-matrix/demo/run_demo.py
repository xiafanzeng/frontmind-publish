"""Reproduce this saved AI decision run; no model/network/application invocation.

AI decisions are an explicit saved input, not generated by this deterministic
runner. Running again revalidates them; it does not claim a new AI generation.
"""
import argparse
from copy import deepcopy
from datetime import datetime, timezone, timedelta
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import sys

ROOT=Path(__file__).resolve().parent
TZ=timezone(timedelta(hours=8))


def load(path): return json.loads(path.read_text(encoding='utf-8'))
def save(path,value): path.write_text(json.dumps(value,ensure_ascii=False,indent=2,allow_nan=False)+'\n',encoding='utf-8')
def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def now(): return datetime.now(TZ).isoformat(timespec='seconds')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workbook',type=Path,help='Original XLSX; omit only to revalidate preserved workbook.json')
    parser.add_argument('--as-of',help='Timezone-aware timestamp; defaults to the real run time in Asia/Shanghai')
    args=parser.parse_args()
    as_of=args.as_of or now()
    parsed=datetime.fromisoformat(as_of.replace('Z','+00:00'))
    if parsed.tzinfo is None:raise ValueError('as_of requires a timezone')
    log={'schemaVersion':1,'startedAt':now(),'as_of':as_of,'python':platform.python_version(),
        'executionScope':'offline_skill_only','modelDecisionOrigin':'AI assistant read the original workbook titles and Skill rules, then authored saved decisions; no external model API was invoked.',
        'steps':[],'projectTestsExecuted':False,'applicationBuildExecuted':False,'deployed':False}
    origin=load(ROOT/'skill-origin.json')
    for relative,expected in origin['sha256'].items():
        if sha(ROOT/'skill-original'/relative)!=expected:
            raise RuntimeError('Original Skill file changed: '+relative)
    log['originalSkillCheck']={'status':'byte_identical_to_reference','fileCount':len(origin['sha256'])}
    env=dict(os.environ,PYTHONIOENCODING='utf-8',PYTHONDONTWRITEBYTECODE='1')
    def execute(label,argv,output=None,expected_code=0,expected_status=None):
        if output:
            destination=(ROOT/output).resolve()
            if ROOT/'outputs' not in destination.parents:raise ValueError('Only owned output artifacts may be replaced')
            if destination.exists():destination.unlink()
        started=now()
        completed=subprocess.run([sys.executable,'-B',*argv],cwd=ROOT,env=env,capture_output=True,text=True,encoding='utf-8')
        entry={'step':label,'command':['python','-B',*argv],'startedAt':started,'finishedAt':now(),
            'exitCode':completed.returncode,'stdout':completed.stdout,'stderr':completed.stderr}
        if completed.returncode==0 and output and (ROOT/output).is_file():
            result=load(ROOT/output);entry['businessStatus']=result.get('status');entry['errors']=result.get('errors',[])
            entry['output']=output;entry['outputSha256']=sha(ROOT/output)
        log['steps'].append(entry)
        save(ROOT/'outputs/run-record.json',log)
        if completed.returncode!=expected_code:raise RuntimeError(f'{label}: unexpected exit {completed.returncode}')
        if expected_status is not None and entry.get('businessStatus')!=expected_status:raise RuntimeError(f'{label}: unexpected business status {entry.get("businessStatus")}')
        return entry
    if args.workbook:
        execute('parse_original_four_sheet_workbook',['convert_workbook.py',str(args.workbook.resolve()),'inputs/workbook.json'])
    execute('prepare_nonpurchasable_observation_attributes',['prepare_input.py'])
    execute('original_skill_candidate_extraction',['skill-original/scripts/planner.py','--input','inputs/matrix-input.json',
        '--stage','matrix','--as-of',as_of,'--output','outputs/candidates.json'],
        'outputs/candidates.json',expected_status='needs_ai_decisions')
    execute('original_skill_validate_ai_matrix',['skill-original/scripts/planner.py','--input','inputs/matrix-input.json',
        '--decisions','inputs/ai-matrix-decisions.json','--stage','matrix','--as-of',as_of,'--output','outputs/matrix.json'],
        'outputs/matrix.json',expected_status='complete')
    save(ROOT/'inputs/formal-budget-decisions.json',{'budget_plans':[]})
    # Deliberately do not fabricate resource IDs to get through the original
    # publication-only rebind. Its real failure is preserved, then the separate
    # research contract performs the explicitly authorized research second stage.
    formal=execute('original_skill_publication_budget_compatibility',['skill-original/scripts/planner.py',
        '--input','inputs/budget-input.json','--decisions','inputs/formal-budget-decisions.json','--stage','budget',
        '--matrix','outputs/matrix.json','--as-of',as_of,'--output','outputs/formal-budget.json'],
        'outputs/formal-budget.json',expected_code=2)
    failure=json.loads(formal['stderr'])
    if failure.get('status')!='invalid_input' or not failure.get('errors'):raise RuntimeError('Unexpected original Skill budget boundary result')
    formal['businessStatus']=failure['status'];formal['errors']=failure['errors']
    save(ROOT/'outputs/formal-budget-compatibility.json',{'cliOutputWritten':False,'exitCode':formal['exitCode'],'stderrResult':failure,
        'explanation':'Original publication budget requires a resource identity for catalog reference rebinding. Raw observation candidates have none. No formal budget plan is fabricated.'})
    execute('validate_ai_research_combinations',['research_combinations.py','--input','inputs/budget-input.json',
        '--matrix','outputs/matrix.json','--decisions','inputs/ai-research-combinations.json','--as-of',as_of,
        '--output','outputs/research-combinations.json'],'outputs/research-combinations.json',expected_status='research_complete')
    matrix=load(ROOT/'outputs/matrix.json');research=load(ROOT/'outputs/research-combinations.json')
    if matrix['errors'] or research['errors']:raise RuntimeError('Do not publish an invalid result')
    result=deepcopy(matrix)
    result.pop('research_only',None);result.pop('pending_items',None);result.pop('snapshot',None)
    result['scope'].pop('input_snapshot',None)
    result['matrix']['candidates']=[c for c in result['matrix']['candidates'] if c.get('semantic_decision_validated')]
    # The public artifact preserves direct reference records only. The complete
    # 502-row observation corpus and matrix stay in inputs/ and outputs/.
    for candidate in result['matrix']['candidates']:
        context=candidate['attributes']['observation_context']
        originals=context['records'];context['source_row_count']=len(originals)
        context['records']=deepcopy(originals[:1]);context['projection']='first source row; all rows archived in inputs/matrix-input.json'
        candidate.pop('attribute_variants',None)
        candidate['observation_provenance']={'file':context['source_file'],'sha256':context['source_sha256'],
            'sheet':'详细表格','rows':[r['sourceRow'] for r in originals]}
    for layer in result['matrix']['layers']:
        if layer['role']=='regional':
            layer['reason_summary']='演示目标明确为全国，且原样本没有可验证的媒体地域覆盖属性；本层保留为空，不按公司地名或域名推断覆盖。'
    result['limitations']=[
        '本结果是 AI 阅读原始样本后提交决定、经本地 Skill 规则复核的预生成研究样本，不是在线模型任务。',
        '502 行原始观察保留重复，缺回答与账号身份；没有精确引用证据或独立行业汇总。',
        '所有候选都是研究来源，资源映射、报价、稿件与发布条件未知；矩阵角色不表示可购买。',
        '研究组合只校验成员与用途；总价、余额及预算可行性未知，不能加入真实购物车。',
        '原始标题中的资质、排名和权威表述未独立核验，不是本次结论。']
    result['research_combinations']=research['research_combinations']
    result['research_revision']=research['research_revision']
    result['report']={k:deepcopy(result[k]) for k in ('status','plan_id','plan_version','matrix_version','scope','source_analysis',
        'matrix','budget_plans','research_combinations','research_revision','limitations','warnings','minimum_known_cost','errors')}
    workbook=load(ROOT/'inputs/workbook.json');batch=workbook['batch'];recon=workbook['provenance']['reconciliation']
    context=load(ROOT/'inputs/demo-context.json');context['form']['questions']=context['form']['questions'].split('\n')
    artifact={'schemaVersion':1,'generatedAt':as_of,'source':{'file':batch['sourceFile'],'sha256':batch['sourceSha256'],
        'period':batch['period'],'recordCount':recon['records'],'groupCount':recon['mediaGroups'],
        'contentUrlCount':recon['contentUrls'],'models':list(recon['models'])},
        'assumptions':context['assumptions'],'form':context['form'],'result':result,
        'research_combinations':deepcopy(research['research_combinations']),
        'research_revision':research['research_revision'],'projection':'Only validated recommendations; complete raw input and Skill output archived alongside.',
        'execution':{'matrix':'original_skill_complete','researchCombinations':research['status'],
            'formalBudget':'not_available_for_unbound_observations','runtimeVerification':'not_executed'}}
    save(ROOT/'yihang-demo.json',artifact)
    hashes={str(path.relative_to(ROOT)).replace('\\','/'):sha(path) for path in sorted(ROOT.rglob('*'))
        if path.is_file() and path.name not in ('run-record.json','artifact-manifest.json') and '__pycache__' not in path.parts}
    save(ROOT/'outputs/artifact-manifest.json',{'schemaVersion':1,'as_of':as_of,'sha256':hashes})
    log.update(finishedAt=now(),status='offline_sample_generated',
        matrixStatus=matrix['status'],matrixVersion=matrix['matrix_version'],planId=matrix['plan_id'],planVersion=matrix['plan_version'],
        recommendedCandidates=len(result['matrix']['candidates']),researchStatus=research['status'],researchCombinations=len(research['research_combinations']),
        originalFormalBudgetStatus=failure['status'],publicArtifactSha256=sha(ROOT/'yihang-demo.json'),
        manifestSha256=sha(ROOT/'outputs/artifact-manifest.json'))
    save(ROOT/'outputs/run-record.json',log)
    print(json.dumps({k:log[k] for k in ('status','matrixStatus','recommendedCandidates','researchStatus','researchCombinations','originalFormalBudgetStatus','as_of')},ensure_ascii=False))


if __name__=='__main__':
    try:main()
    except Exception as exc:
        record_path=ROOT/'outputs/run-record.json'
        record=load(record_path) if record_path.exists() else {'steps':[]}
        record.update(status='offline_generation_failed',finishedAt=now(),failure=str(exc),
            priorPublicArtifactRetained=(ROOT/'yihang-demo.json').exists(),
            outputPolicy='Do not present a retained prior public artifact as a successful result of this failed run.')
        save(record_path,record)
        raise
